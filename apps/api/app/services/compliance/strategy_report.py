from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from decimal import Decimal
from typing import Mapping


RETENTION_MIGRATION_REVISION = "20260501_0012"


@dataclass(frozen=True)
class StrategyBacktestEvidence:
    command: str
    start_at: datetime
    end_at: datetime
    sample_count: int
    sharpe_ratio: Decimal
    max_drawdown: Decimal
    total_return: Decimal
    win_rate: Decimal


@dataclass(frozen=True)
class CapitalAllocationDecision:
    decided_at: datetime
    actor: str
    old_fraction: Decimal
    new_fraction: Decimal
    reason: str
    audit_log_id: str | None = None


@dataclass(frozen=True)
class StrategyReportContext:
    strategy_name: str
    strategy_version: str
    generated_at: datetime
    generated_by: str
    backtest: StrategyBacktestEvidence
    gray_release_summary: Mapping[str, object] = field(default_factory=dict)
    capital_allocation_decisions: tuple[CapitalAllocationDecision, ...] = ()
    live_readiness_decisions: tuple[str, ...] = ()


def _as_utc(value: datetime) -> datetime:
    if value.tzinfo is None:
        raise ValueError("strategy report datetimes must be UTC-aware")
    return value.astimezone(UTC)


def _format_decimal(value: Decimal) -> str:
    return format(value, "f")


def _format_value(value: object) -> str:
    if isinstance(value, Decimal):
        return _format_decimal(value)
    if isinstance(value, datetime):
        return _as_utc(value).isoformat()
    return str(value)


def build_strategy_report_template() -> str:
    return "\n".join(
        [
            "# Strategy Report: <strategy_name> <strategy_version>",
            "",
            "Generated at: <UTC datetime>",
            "Generated by: <actor>",
            "",
            "## Strategy Identity",
            "- Strategy name: <strategy_name>",
            "- Strategy version: <strategy_version>",
            "",
            "## Backtest Evidence",
            "- Command: <verification command>",
            "- Window: <UTC start> to <UTC end>",
            "- Sample count: <integer>",
            "- Sharpe ratio: <Decimal>",
            "- Max drawdown: <Decimal>",
            "- Total return: <Decimal>",
            "- Win rate: <Decimal>",
            "",
            "## Gray-Release Evidence",
            "- observation_count=<integer>",
            "- running_days=<Decimal>",
            "- sharpe_deviation=<Decimal>",
            "- risk_event_count=<integer>",
            "- acceptance_ready=<bool>",
            "",
            "## Live-Readiness Decisions",
            "- <decision summary with actor, UTC timestamp, old value, new value, and reason>",
            "",
            "## Capital Allocation Changes",
            "- decided_at=<UTC datetime> actor=<actor> old_fraction=<Decimal> new_fraction=<Decimal> reason=<reason> audit_log_id=<id>",
            "",
            "## Retention And Audit Evidence",
            f"- retention migration: {RETENTION_MIGRATION_REVISION}",
            "- audit_logs append-only",
            "- trading evidence retained for at least 5 years",
        ]
    )


def build_strategy_report_markdown(context: StrategyReportContext) -> str:
    generated_at = _as_utc(context.generated_at)
    backtest_start = _as_utc(context.backtest.start_at)
    backtest_end = _as_utc(context.backtest.end_at)
    lines = [
        f"# Strategy Report: {context.strategy_name} {context.strategy_version}",
        "",
        f"Generated at: {generated_at.isoformat()}",
        f"Generated by: {context.generated_by}",
        "",
        "## Strategy Identity",
        f"- Strategy name: {context.strategy_name}",
        f"- Strategy version: {context.strategy_version}",
        "",
        "## Backtest Evidence",
        f"- Command: {context.backtest.command}",
        f"- Window: {backtest_start.isoformat()} to {backtest_end.isoformat()}",
        f"- Sample count: {context.backtest.sample_count}",
        f"- Sharpe ratio: {_format_decimal(context.backtest.sharpe_ratio)}",
        f"- Max drawdown: {_format_decimal(context.backtest.max_drawdown)}",
        f"- Total return: {_format_decimal(context.backtest.total_return)}",
        f"- Win rate: {_format_decimal(context.backtest.win_rate)}",
        "",
        "## Gray-Release Evidence",
    ]
    if context.gray_release_summary:
        for key in sorted(context.gray_release_summary):
            lines.append(f"- {key}={_format_value(context.gray_release_summary[key])}")
    else:
        lines.append("- No gray-release summary attached.")

    lines.extend(["", "## Live-Readiness Decisions"])
    if context.live_readiness_decisions:
        lines.extend(f"- {decision}" for decision in context.live_readiness_decisions)
    else:
        lines.append("- No live-readiness decision attached.")

    lines.extend(["", "## Capital Allocation Changes"])
    if context.capital_allocation_decisions:
        for decision in context.capital_allocation_decisions:
            decided_at = _as_utc(decision.decided_at)
            audit_log = decision.audit_log_id or "not-recorded"
            lines.append(
                "- "
                f"decided_at={decided_at.isoformat()} "
                f"actor={decision.actor} "
                f"old_fraction={_format_decimal(decision.old_fraction)} "
                f"new_fraction={_format_decimal(decision.new_fraction)} "
                f"reason={decision.reason} "
                f"audit_log_id={audit_log}"
            )
    else:
        lines.append("- No capital allocation change attached.")

    lines.extend(
        [
            "",
            "## Retention And Audit Evidence",
            f"- retention migration: {RETENTION_MIGRATION_REVISION}",
            "- audit_logs append-only",
            "- trading evidence retained for at least 5 years",
        ]
    )
    return "\n".join(lines)
